@pytest.mark.parametrize("revision", sorted(EVIDENCE))
def test_historical_downgrade_refuses_while_immutable_evidence_exists(database, revision):
    command.upgrade(database.config, revision)
    for statement in EVIDENCE[revision]:
        run(database, statement)
    with pytest.raises(RuntimeError, match=f"Downgrade below {revision} refused"):
        command.downgrade(database.config, f"{int(revision) - 1:04d}")
    database.connection.rollback()
    assert version(database) == revision


def test_spatial_history_that_an_upgrade_reproduces_can_still_be_downgraded(database):
    command.upgrade(database.config, "0022")
    network = uuid.uuid4()
    run(database, "INSERT INTO networks (network_id, workspace_id, name) VALUES (:id, :id, 'n')", id=network)
    run(database, "INSERT INTO network_spatial_scenes (network_id, revision, scene) VALUES (:id, 3, '{\"a\": 1}')",
        id=network)
    run(database, "INSERT INTO network_spatial_scene_revisions (network_id, revision, scene, origin) "
                  "VALUES (:id, 3, '{\"a\": 1}', 'baseline')", id=network)
    command.downgrade(database.config, "0021")
    command.upgrade(database.config, "0022")
    assert run(database, "SELECT revision, origin FROM network_spatial_scene_revisions") == [(3, "baseline")]
